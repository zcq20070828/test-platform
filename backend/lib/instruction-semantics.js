/**
 * 指令语义判定（2026-11-25）
 *
 * 为什么单独抽出来
 *
 * 「继续」「继续优化登录模块的用例」「经过3轮还没达标，针对性修改吧」
 * 这三句要判的东西完全不同，但用长度切分是错的：
 *
 *   用户明确指出的问题：「不能根据输入的长度来判断，要根据输入的内容来判断，
 *   对输入内容进行语义理解来判断」。
 *
 * 长度和语义没有必然关系：
 *   - 「继续」（2 字）                      → 纯指代，指上一个任务
 *   - 「基于上一步的需求分析结果生成测试用例」（18 字） → 有具体产出目标，是真实任务
 *   - 「经过3轮都还没达到审核通过标准，那就针对性修改吧」（24 字）→ 有修改对象，是真实任务
 *   - 「继续把登录模块的边界值用例补到 20 条」（20 字）  → 带明确范围，是新的具体指令
 *
 * 所以判据是「这句话里有没有**独立于上文的信息**」：
 *   只有指代词 + 动作词，没有任何具体对象 → 空壳，必须靠上文才知道做什么；
 *   只要出现具体对象（模块名、编号、数量、字段、条件），这句话本身就成立，不该被当成续做。
 */

/**
 * 指代词：把「做什么」指向对话上文
 *
 * 单独出现时不含信息，必须靠上文解析。
 */
const ANAPHORA_RE = /刚才|刚刚|上面|之前|上次|上一个|前一个|那份|这份|该需求|同样|基于上|在此基础上|针对这份|针对上面|接着|继续/;

/**
 * 动作词：说明「要做什么类型的动作」，但不说明对象
 */
const ACTION_RE = /优化|改进|完善|修订|调整|修改|改|重写|改写|润色|补充|精简|细化|生成|产出|输出|重做|重跑|再来|再生成/;

/**
 * 具体信息标记：这些出现就说明句子自带对象，不是空壳
 *
 * 每一类都是「独立于上文就能指认的东西」：
 *   - 用例/需求编号（TC-001 / FR-002）
 *   - 数量（20 条、3 轮、5 次）
 *   - 「把 X 改成 Y」这类带具体对象的改写
 *   - 「X 的 Y」结构
 *   - 业务/测试领域的实质名词（登录、支付、边界值、审核通过标准…）
 */
const CONCRETE_INFO_PATTERNS = [
  // 编号
  /\b(?:TC|FR|NFR|API|AI|DC|NW|BE|PE|UC|CASE|AC|ST)[-_]?\d{1,4}\b/i,
  // 数量（2026-11-25 补「轮/次/遍」——实测「经过3轮」被漏掉）
  /\d+\s*(?:条|个|项|步|处|种|类|页|行|列|轮|次|遍|版|批)/,
  // 「把 X 改成 Y」这类带具体对象的改写
  /把\s*\S{2,}/,
  // 「X 的 Y」结构：说明提到了具体对象
  /[\u4e00-\u9fa5A-Za-z]{2,}\s*的\s*[\u4e00-\u9fa5A-Za-z]{2,}/,
];

/**
 * 业务领域对象（2026-11-25）
 *
 * 只认**业务模块/实体**（登录、支付、订单…），这些词指向「这次要做的新东西」。
 *
 * 不认属性词（状态码/步骤/字段/预期结果/标准/覆盖率），因为它们在「改进要求」
 * 里出现是正常的——那说的是「要改成什么样」，不是「改哪个新对象」。
 * 实测这条区分很关键：「从审核结果看，该用例还有优化空间，继续优化…
 * 请补充明确的状态码和字段名」如果把「状态码」算作对象，真实的改稿指令
 * 就会被误判成新任务，导致从需求重跑一遍。
 *
 * 实测对照：
 *   「继续优化登录模块的用例」→ 含「登录」，是业务对象 → 独立
 *   「经过3轮都还没达到审核通过标准，那就针对性修改吧」→ 无业务对象 → 改上文
 */
// 交付物名词（2026-11-25 补）：指明要基于/产出哪个产物，也是明确对象
// 实测「基于上一步的需求分析结果生成测试用例」：开头「基于上」会被指代词命中，
// 但这里的「需求分析结果」是明确的产物，句子独立成立，不该当成改上文。
const BUSINESS_OBJECT_RE = /登录|注册|支付|订单|购物车|结算|退款|发票|账户|钱包|积分|优惠券|会员|商品|库存|物流|评价|客服|消息|通知|搜索|收藏|分享|权限|角色|组织|部门|审批|工单|合同|报表|对账|风控|实名|认证|绑定|解绑|换绑|扫码|核销|预约|签到|任务|日历|相册|备份|上传|下载|同步|鉴权|令牌|会话|网关|中间件|微服务|容器|集群|主从|分库|分表|需求分析|测试方案|测试计划|用例集|测试用例|测试报告|缺陷报告|执行结果|分析报告|方案|报告/;

/**
 * 纯指代/纯动作的「极简指令」白名单
 *
 * 这些整句本身就是空壳——它们没有任何对象，仅仅是把上文接下去。
 * 用白名单而不是长度判断，因为长度和语义无关：
 *   「继续把登录模块的边界值用例补到 20 条」20 字，但有对象，不是空壳。
 *
 * 注意：这是**精确匹配整句**（允许前后有标点/语气词），
 * 不做「以……开头」匹配——那样又会退化成按形式切分。
 */
const BARE_INSTRUCTION_RE = /^[\s，。,.！!？?~～]*(?:请|麻烦)?\s*(?:继续|接着|接着做|接着来|往下|继续做|继续吧|继续优化|继续改进|继续完善|继续修改|继续调整|优化一下|优化优化|改进一下|完善一下|调整一下|再来|再来一次|再来一遍|重做|重跑|重新做|重新生成|再生成|重写|再改改|改改|改一下)[\s，。,.！!？?~～]*$/;

/**
 * 判断一句话是否「自带足够信息、能独立成立」
 *
 * @param {string} text
 * @returns {{selfContained:boolean, reason:string}}
 */
export function assessSelfContained(text) {
  const t = String(text || '').trim();
  if (!t) return { selfContained: false, reason: '空输入' };

  // 1) 整句就是极简指令 → 空壳（最确定的判据，先判）
  if (BARE_INSTRUCTION_RE.test(t)) {
    return { selfContained: false, reason: '整句是纯指代/纯动作，没有说明对象' };
  }

  // 2) 有指代词，且没有**业务对象** → 是在改上文，不是新任务
  //
  // 这一条要排在「具体信息」之前（2026-11-25）：
  //
  //   「从审核结果看，该用例还有优化空间，继续优化。具体来说预期结果不够具体，
  //    请补充明确的状态码和字段名」
  // 句中有「继续」指代上文，有「优化」动作，也有「3轮」「预期结果的」这类
  // 会被 CONCRETE_INFO_PATTERNS 命中的片段——但那些是**改进要求的描述**，
  // 不是新任务的对象。它改的就是上一份交付物。
  //
  // 判据：有指代词 + 无业务领域对象 → 按改上文处理。
  // 反例（应当独立）：「继续优化登录模块的用例」含「登录」，是明确的业务对象。
  const hasAnaphora = ANAPHORA_RE.test(t);
  const hasBusinessObject = BUSINESS_OBJECT_RE.test(t);
  if (hasAnaphora && !hasBusinessObject) {
    return { selfContained: false, reason: '有指代词且未指明新的业务对象，是在改上文' };
  }

  // 3) 「对现有结果不满意 + 要求修改」→ 是在改上文（2026-11-25）
  //
  // 实测「经过3轮都还没达到审核通过标准，那就针对性修改吧」：
  // 没有指代词，但「都还没达到」说明在评价**已有产物**的结果，
  // 「针对性修改」说明动作对象就是那个产物。这类句子说的全是上文，
  // 不能因为它提到「标准」「3轮」就当新任务。
  //
  // 判据：出现「结果性评价」（还没达到/没通过/不够/偏差/仍然…）
  //      + 出现修改动作 → 指向上文的已有产物。
  const RESULT_EVAL_RE = /还没达到|还没通过|没达到|没通过|未达到|未通过|不合格|不达标|不够|仍需|还是有|仍然有|仍然存在|存在问题|有偏差|不理想|不满意|偏高|偏低|太虚|太笼统|不具体/;
  if (RESULT_EVAL_RE.test(t) && ACTION_RE.test(t)) {
    return { selfContained: false, reason: '评价已有产物的结果并要求修改，指向上文' };
  }

  // 3) 含具体对象 → 独立成立
  const concreteHit = CONCRETE_INFO_PATTERNS.find((re) => re.test(t));
  if (concreteHit) {
    return { selfContained: true, reason: '包含具体对象，句子独立成立' };
  }

  // 4) 其余（不是极简指令、也没有对象标记）
  //    保守判为独立——宁可把「继续 xxx」当成真实任务（最多多跑一次），
  //    也不要把真实任务当成空壳（会指错对象、重跑错东西）。
  return { selfContained: true, reason: '非极简指令，按独立输入处理' };
}

/**
 * 是不是「纯续做指令」——只靠上文才有意义的指令
 *
 * 用于两处：
 *   1. 新提交的输入是不是「继续」（决定要不要沿用上一个任务的智能体）
 *   2. 库里的某个历史任务的 input 本身也是空壳（不能把它当需求注入）
 *
 * 判据完全基于内容语义，不看长度。
 *
 * @param {string} text
 * @returns {boolean}
 */
export function isPureContinuation(text) {
  const t = String(text || '').trim();
  if (!t) return true;
  const { selfContained } = assessSelfContained(t);
  return !selfContained;
}

/**
 * 从「继续」类输入里提取可能的修改意图（优化改稿 vs 重新生成）
 *
 * 「继续优化」和「重新生成」的注入内容必须不同：
 *   优化 → 给完整交付物 + 审核意见，让模型在原稿上改
 *   重做 → 给需求原文，让模型重新产出
 *
 * @param {string} text
 * @returns {'refine'|'regenerate'|null}
 */
export function detectContinuationKind(text) {
  const t = String(text || '');
  if (!t.trim()) return null;
  const regenerate = /重新生成|重做|重跑|重新做|再来一次|再生成一?份|重新出一?份|重出一?份|从头/;
  if (regenerate.test(t)) return 'regenerate';
  // 改稿动词且不含"重新"语义 → 优化
  if (ACTION_RE.test(t)) return 'refine';
  return null;
}

export default {
  assessSelfContained,
  isPureContinuation,
  detectContinuationKind,
};
